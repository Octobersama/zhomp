export function findMissingModelHubTranslations(dictionary: Readonly<Record<string, unknown>>): string[] {
	return MODEL_HUB_TEXT_KEYS.filter(key => {
		if (!Object.hasOwn(dictionary, key)) return true;
		const value = dictionary[key];
		return typeof value !== "string" || value.length === 0 || value === key;
	});
}
