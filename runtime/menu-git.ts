import type { MenuModule } from "./menu-catalog";

type GitMenuPatch = MenuModule["patches"][number];

function menuText(source: string, values?: string): string {
	const key = JSON.stringify(source);
	return values === undefined ? `__zhompMenuText(${key})` : `__zhompMenuText(${key}, ${values})`;
}

function templateText(source: string): string {
	return "${" + menuText(source) + "}";
}

function patch(before: string, after: string, count = 1): GitMenuPatch {
	return { before, after, count };
}

